const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const core=require('../quiz-core.js');
const root=path.resolve(__dirname,'..');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'data.js'),'utf8'),context);
const data=JSON.parse(JSON.stringify(context.window.ISAAD));
const banks=core.buildBanks(data);
assert.equal(Object.keys(banks).length,7);
assert.equal(banks.exam.pool.length,80);
assert.equal(banks.exam.questions.length,0);
assert.equal(data.practice.length,30);
assert.equal(new Set([...data.practice,...data.exam].map(q=>q.id)).size,110);
const practiceStems=new Set(data.practice.map(q=>q.stem));
assert(data.exam.every(q=>!practiceStems.has(q.stem)));
let seed=1234567;
const rng=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296;};
const poolSnapshot=JSON.stringify(data.exam);
const first=core.createExamRound(data.exam,{},rng);
const second=core.createExamRound(data.exam,first.history,rng);
const third=core.createExamRound(data.exam,second.history,rng);
const ids=round=>round.questions.map(q=>q.id);
const sortedIds=round=>[...ids(round)].sort();
function validateRound(round){
  assert.equal(round.questions.length,40);
  assert.equal(new Set(ids(round)).size,40,'No duplicate question in one round');
  assert.deepEqual([1,2,3,4,5,6].map(m=>round.questions.filter(q=>q.module===m).length),[7,7,7,6,6,7]);
  assert(round.questions.every(q=>data.exam.some(item=>item.id===q.id)));
}
[first,second,third].forEach(validateRound);
assert(ids(second).every(id=>!new Set(ids(first)).has(id)),'Second draw exhausts the unseen half before repeating');
assert.equal(new Set([...ids(first),...ids(second)]).size,80);
assert.equal(second.history.seenIds.length,80);
assert.equal(third.history.cycle,2);
assert.equal(third.history.seenIds.length,40);
assert.notDeepEqual(sortedIds(second),sortedIds(third));
const forced=core.createExamRound(data.exam,{lastIds:ids(core.createExamRound(data.exam,{},()=>0))},()=>0);
assert.notDeepEqual(sortedIds(forced),sortedIds(core.createExamRound(data.exam,{},()=>0)),'An identical selection is replaced even with a constant random source');
validateRound(forced);
let history={};
for(let i=0;i<100;i++){const round=core.createExamRound(data.exam,history,rng);validateRound(round);if(history.lastIds)assert.notDeepEqual([...history.lastIds].sort(),sortedIds(round));history=round.history;}
assert.equal(JSON.stringify(data.exam),poolSnapshot,'Sampling does not mutate the authored pool or answer keys');
banks.exam.questions=first.questions;
let checks=0;
for(const bank of Object.values(banks)){
  const a=core.createAttempt(bank.questions.length);
  assert.equal(core.submit(bank,a),false,'Must not submit unanswered questions');
  assert.equal(core.choose(bank,a,-1),false);
  assert.equal(core.choose(bank,a,4),false);
  bank.questions.forEach((q,i)=>{a.current=i;assert.equal(core.choose(bank,a,q.correct),true);if(bank.mode==='practice')assert.equal(core.choose(bank,a,(q.correct+1)%4),false,'Graded practice answers stay locked');});
  assert.equal(core.score(bank,a),bank.questions.length);
  assert.equal(core.missing(a).length,0);
  assert.equal(core.submit(bank,a),true);
  assert.equal(core.choose(bank,a,0),false,'Submitted exam answers stay locked');
  const restored=core.restoreState({read:[1,1,2,0,99],attempts:{[bank.id]:a}},banks);
  assert.deepEqual(restored.read,[1,2]);
  if(bank.mode==='practice')assert.deepEqual(restored.attempts[bank.id],a,'Practice progress survives reload');
  else assert.equal(restored.attempts.exam,undefined,'Reopening never restores old exam answers');
  checks++;
}
const exam=banks.exam,a=core.createAttempt(40);
exam.questions.forEach((q,i)=>{a.current=i;core.choose(exam,a,q.correct);});
a.current=0;assert(core.choose(exam,a,(exam.questions[0].correct+1)%4),'Exam answers may change before submission');
assert.equal(core.score(exam,a),39);
assert.deepEqual(core.moduleScores(exam,a).map(x=>x.total),[7,7,7,6,6,7]);
assert.equal(core.moduleScores(exam,a).reduce((s,x)=>s+x.correct,0),39);
assert.equal(core.submit(exam,a),true);
const damaged={read:['1',6],examHistory:{seenIds:['unknown',first.questions[0].id,first.questions[0].id],lastIds:[null],cycle:-1},attempts:{'practice-1':{answers:[null,0,1,2,9],graded:[true,true,true,true,true],current:200,submitted:true}}};
const repaired=core.restoreState(damaged,banks);
assert.equal(repaired.attempts['practice-1'].submitted,false);
assert.equal(repaired.attempts['practice-1'].current,4);
assert.equal(repaired.attempts['practice-1'].answers[4],null);
assert.deepEqual(repaired.examHistory.seenIds,[first.questions[0].id]);
assert.deepEqual(repaired.read,[6]);
assert.deepEqual(core.restoreState({attempts:{exam:{answers:[]}}},banks).attempts,{});
const persistent=core.persistentState({read:[1],examHistory:first.history,attempts:{exam:a,'practice-1':core.createAttempt(5)}});
assert.equal(persistent.attempts.exam,undefined,'Only history, not exam answers, is persisted');
const reopened=core.restoreState(JSON.parse(JSON.stringify(persistent)),banks);
const reopenedRound=core.createExamRound(data.exam,reopened.examHistory,rng);
assert(ids(reopenedRound).every(id=>!new Set(ids(first)).has(id)),'Reopening draws from unseen questions');
assert.equal(reopened.attempts.exam,undefined);
assert(reopened.attempts['practice-1']);
const migrated=core.restoreState({attempts:{exam:{answers:Array(40).fill(0)}}},banks);
assert.equal(migrated.examHistory.seenIds.length,40);
assert(core.createExamRound(data.exam,migrated.examHistory,rng).questions.every(q=>!data.legacyExamIds.includes(q.id)),'Existing users see the new half first');
// Two tabs opened before either starts must read the latest persisted history.
const tabA=core.restoreState(null,banks),tabB=core.restoreState(null,banks);
const roundA=core.createExamRound(data.exam,tabA.examHistory,rng);
tabA.examHistory=roundA.history;
let shared=JSON.parse(JSON.stringify(core.persistentState(tabA)));
tabB.examHistory=core.restoreState(shared,banks).examHistory;
const roundB=core.createExamRound(data.exam,tabB.examHistory,rng);
assert(ids(roundB).every(id=>!new Set(ids(roundA)).has(id)),'A second tab draws the unseen half');
tabB.examHistory=roundB.history;
shared=JSON.parse(JSON.stringify(core.persistentState(tabB)));
const laterPracticeSave=core.persistentState(tabA,core.cleanHistory(shared.examHistory,data.exam));
assert.equal(laterPracticeSave.examHistory.seenIds.length,80,'A practice save cannot discard another tab’s draw history');
for(const q of [...data.practice,...data.exam]){assert.equal(q.options.length,4);assert.equal(q.shades[q.correct],'ขาว');assert(q.shades.includes('เทา'));assert(q.shades.includes('ดำ'));}
