const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const miracle=require('../miracle.js');
const root=path.resolve(__dirname,'..');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'miracle-data.js'),'utf8'),context);
const data=JSON.parse(JSON.stringify(context.window.ISAAD_MIRACLE));
assert.equal(data.minutes,10);
assert.deepEqual(data.modules.map(m=>m.id),[1,2,3,4,5,6]);
assert.equal(miracle.plan.reduce((s,p)=>s+p.seconds,0)+30,600);
const html=miracle.render(data.modules);
assert.equal((html.match(/class="miracle-module"/g)||[]).length,6);
assert.equal((html.match(/<figure /g)||[]).length,6);
assert.equal((html.match(/<h1>/g)||[]).length,1);
assert(!html.includes('undefined'));
assert(!html.includes('<script'));
const ids=[...html.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length);
for(const [,target]of html.matchAll(/data-scroll="([^"]+)"/g))assert(ids.includes(target),`Missing scroll target ${target}`);
for(const m of data.modules){assert(html.includes(`ISAAD-${m.id}-2026.pdf`));assert(html.includes(`#module/${m.id}`));assert.equal(m.points.length,4);}
const attack=JSON.parse(JSON.stringify(data.modules));
attack[0].bigPicture='<img src=x onerror=alert(1)>';
assert(miracle.render(attack).includes('&lt;img src=x onerror=alert(1)&gt;'),'Summary text is rendered as text, never executable markup');
assert.throws(()=>miracle.render(data.modules.slice(1)));
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(index.includes('href="#miracle"'));
assert(index.indexOf('miracle-data.js')<index.indexOf('app.js'));
assert(index.indexOf('miracle.js')<index.indexOf('app.js'));
if(process.argv[2])fs.writeFileSync(process.argv[2],html,'utf8');
console.log(JSON.stringify({modules:6,points:24,diagrams:6,readingPlanSeconds:600,checks:['render-all-modules','scroll-targets','source-references','script-order','safe-text','complete-data'],status:'passed'}));
